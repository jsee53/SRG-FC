-- 일정 하나에 여러 경기 지원
-- 팀 배정과 POM 투표를 일정 단위에서 경기(match) 단위로 변경

create table if not exists event_matches (
  id bigint generated by default as identity primary key,
  event_id bigint not null references events (id) on delete cascade,
  match_number int not null,
  created_at timestamptz not null default now(),
  unique (event_id, match_number)
);

alter table event_matches enable row level security;

create policy "event matches are viewable by everyone"
  on event_matches for select using (true);
create policy "event managers can add matches"
  on event_matches for insert with check (is_event_manager());
create policy "event managers can delete matches"
  on event_matches for delete using (is_event_manager());

-- event_attendees.team_index 대체
create table if not exists match_team_assignments (
  match_id bigint not null references event_matches (id) on delete cascade,
  attendee_id bigint not null references event_attendees (id) on delete cascade,
  team_index int not null,
  primary key (match_id, attendee_id)
);

alter table match_team_assignments enable row level security;

create policy "match team assignments are viewable by everyone"
  on match_team_assignments for select using (true);
create policy "event managers can save match team assignments"
  on match_team_assignments for insert with check (is_event_manager());
create policy "event managers can update match team assignments"
  on match_team_assignments for update using (is_event_manager());
create policy "event managers can delete match team assignments"
  on match_team_assignments for delete using (is_event_manager());

-- 기존 팀 배정은 1경기로 이전
insert into event_matches (event_id, match_number)
select distinct event_id, 1
from event_attendees
where team_index is not null
on conflict (event_id, match_number) do nothing;

insert into match_team_assignments (match_id, attendee_id, team_index)
select em.id, ea.id, ea.team_index
from event_attendees ea
join event_matches em on em.event_id = ea.event_id and em.match_number = 1
where ea.team_index is not null
on conflict (match_id, attendee_id) do update set team_index = excluded.team_index;

-- 투표도 경기 단위로 변경
alter table event_best_player_votes add column if not exists match_id bigint references event_matches (id) on delete cascade;

update event_best_player_votes v
set match_id = em.id
from event_matches em
where em.event_id = v.event_id and em.match_number = 1 and v.match_id is null;

alter table event_best_player_votes drop constraint if exists event_best_player_votes_event_id_voter_id_key;
alter table event_best_player_votes alter column match_id set not null;
alter table event_best_player_votes add constraint event_best_player_votes_match_id_voter_id_key unique (match_id, voter_id);

-- 파라미터 이름이 바뀌어서 삭제 후 재생성
drop function if exists cast_best_player_vote(bigint, bigint);
drop function if exists retract_best_player_vote(bigint);

create or replace function cast_best_player_vote(target_match_id bigint, target_attendee_id bigint)
returns void as $$
declare
  match_event_id bigint;
  event_confirmed boolean;
  voter_attendee_id bigint;
  voter_team_index int;
  candidate_team_index int;
begin
  select event_id into match_event_id from event_matches where id = target_match_id;
  if not found then
    raise exception 'match not found';
  end if;

  select confirmed into event_confirmed from events where id = match_event_id;
  if not found or event_confirmed is not true then
    raise exception 'event not confirmed yet';
  end if;

  select mta.attendee_id, mta.team_index into voter_attendee_id, voter_team_index
    from match_team_assignments mta
    join event_attendees ea on ea.id = mta.attendee_id
    join members m on m.id = ea.member_id
    where mta.match_id = target_match_id and m.user_id = auth.uid();
  if not found then
    raise exception 'you were not an attendee of this match';
  end if;

  if voter_attendee_id = target_attendee_id then
    raise exception 'cannot vote for yourself';
  end if;

  select team_index into candidate_team_index
    from match_team_assignments
    where match_id = target_match_id and attendee_id = target_attendee_id;
  if not found or candidate_team_index is distinct from voter_team_index then
    raise exception 'candidate is not on your team';
  end if;

  insert into event_best_player_votes (event_id, match_id, team_index, voter_id, voted_attendee_id)
  values (match_event_id, target_match_id, voter_team_index, auth.uid(), target_attendee_id)
  on conflict (match_id, voter_id)
  do update set voted_attendee_id = excluded.voted_attendee_id, team_index = excluded.team_index, created_at = now();
end;
$$ language plpgsql security definer;

create or replace function retract_best_player_vote(target_match_id bigint)
returns void as $$
begin
  delete from event_best_player_votes
  where match_id = target_match_id and voter_id = auth.uid();
end;
$$ language plpgsql security definer;

drop function if exists reset_event_teams(bigint);

create or replace function add_event_match(target_event_id bigint)
returns bigint as $$
declare
  next_number int;
  new_id bigint;
begin
  if not is_event_manager() then
    raise exception 'not an event manager';
  end if;

  select coalesce(max(match_number), 0) + 1 into next_number
    from event_matches where event_id = target_event_id;

  insert into event_matches (event_id, match_number) values (target_event_id, next_number)
    returning id into new_id;

  return new_id;
end;
$$ language plpgsql security definer;

create or replace function reset_match_teams(target_match_id bigint)
returns void as $$
begin
  if not is_event_manager() then
    raise exception 'not an event manager';
  end if;

  delete from match_team_assignments where match_id = target_match_id;
  delete from event_best_player_votes where match_id = target_match_id;
end;
$$ language plpgsql security definer;

-- 중간 경기를 지우면 뒤 경기 번호를 앞으로 당김 (match_id는 그대로)
create or replace function delete_event_match(target_match_id bigint)
returns void as $$
declare
  target_event_id bigint;
begin
  if not is_event_manager() then
    raise exception 'not an event manager';
  end if;

  select event_id into target_event_id from event_matches where id = target_match_id;
  if not found then
    raise exception 'match not found';
  end if;

  delete from event_matches where id = target_match_id;

  update event_matches em
  set match_number = ranked.rank
  from (
    select id, row_number() over (order by match_number) as rank
    from event_matches
    where event_id = target_event_id
  ) ranked
  where em.id = ranked.id;
end;
$$ language plpgsql security definer;

